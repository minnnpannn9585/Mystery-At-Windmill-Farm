def img(name):
    """优先使用压缩后的 jpg（体积约 1/8，视觉无差）"""
    jpg = os.path.join(ASSETS, os.path.splitext(name)[0] + ".jpg")
    return jpg if os.path.exists(jpg) else os.path.join(ASSETS, name)


def code(doc, lines, size=8.5):
    tbl = doc.add_table(rows=1, cols=1)
    tbl.alignment = 1
    _fix_tbl_width(tbl, [16.2])
    c = tbl.cell(0, 0)
    shade(c, "F4F6F8")
    cell_margins(c, 100, 100, 160, 120)
    c.paragraphs[0].text = ""
    first = True
    for ln in lines:
        p = c.paragraphs[0] if first else c.add_paragraph()
        first = False
        p.paragraph_format.space_after = Pt(0)
        p.paragraph_format.line_spacing = 1.25
        r = p.add_run(ln if ln else " ")
        set_run_font(r, name="Consolas", size=size, color=RGBColor(0x24, 0x3A, 0x46))
    doc.add_paragraph().paragraph_format.space_after = Pt(2)


